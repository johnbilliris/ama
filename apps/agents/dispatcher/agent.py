"""Sub-agent dispatcher FastAPI app.

Routes
------
* ``GET  /health``                 — liveness/readiness probe.
* ``POST /{role}/invoke``          — invoke a sub-agent.

The six roles are kebab-case (``risk-assessment``, ``resource-allocation``)
to match the URLs the API-side adapters POST to. The handler is shared:
each role contributes a system prompt that frames the question for that
operational discipline, then defers to the shared ``LLMClient`` (Foundry
chat-complete seam in production).

Reply schema (matches ``apps/api/app/services/simulation/sub_agents/_base.py``
``call_agent`` parser):

```
{
  "summary":          str,         # natural-language answer
  "citations":        list[str],   # may be empty
  "prompt_hash":      str | None,  # sha256 of the prompt body, hex
  "model_deployment": str | None,  # Foundry deployment id used
  "invocation_id":    str          # uuid4 hex
}
```
"""

from __future__ import annotations

import hashlib
import logging
import os
from uuid import uuid4

from common.foundry_chat_client import (
    FoundryConfigurationError,
    FoundryGatewayDenied,
    FoundryTransportError,
    LiveFoundryChatClient,
)
from fastapi import FastAPI, HTTPException
from pydantic import BaseModel, Field

logger = logging.getLogger(__name__)

# Canonical kebab-case role set — must stay in lock-step with
# ``apps/api/app/services/simulation/sub_agents/_base.py``::``MODEL_DEPLOYMENT_BY_ROLE``.
_ROLES: frozenset[str] = frozenset(
    {
        "monitoring",
        "planning",
        "risk-assessment",
        "communication",
        "evacuation",
        "resource-allocation",
    }
)

# Per-role system prompt prefix. Kept short and operational; the answer
# itself is generated by the LLM so domain nuance comes from the model
# rather than hard-coded copy.
_ROLE_SYSTEM: dict[str, str] = {
    "monitoring": (
        "You are the Monitoring sub-agent in a disaster-response simulation. "
        "Surface the operational signals and intelligence relevant to the "
        "controller's question. Keep responses concise (2-4 sentences) and "
        "label any assumed data as such."
    ),
    "planning": (
        "You are the Planning sub-agent in a disaster-response simulation. "
        "Outline the next-step planning options the controller should weigh, "
        "in 2-4 sentences. Surface dependencies and decision gates."
    ),
    "risk-assessment": (
        "You are the Risk-Assessment sub-agent in a disaster-response "
        "simulation. Quantify the risks implied by the controller's question "
        "and recommend a risk posture in 2-4 sentences. Flag confidence."
    ),
    "communication": (
        "You are the Communications sub-agent in a disaster-response "
        "simulation. Recommend the warning level, audience, and channel for "
        "the controller's intent in 2-4 sentences. Mark all output as "
        "SIMULATION-ONLY."
    ),
    "evacuation": (
        "You are the Evacuation sub-agent in a disaster-response simulation. "
        "Recommend evacuation priorities, routes, and assembly points in 2-4 "
        "sentences. Note any assumed road-network gaps."
    ),
    "resource-allocation": (
        "You are the Resource-Allocation sub-agent in a disaster-response "
        "simulation. Recommend which resources to deploy, where, and in what "
        "order, in 2-4 sentences. Surface contention or shortfalls."
    ),
}


class InvokeRequest(BaseModel):
    tenant_id: str = Field(..., min_length=1, max_length=128)
    question: str = Field(..., min_length=1, max_length=4000)
    # Forward-compatible: extra fields tolerated to ease contract evolution.
    model_config = {"extra": "allow"}


class InvokeResponse(BaseModel):
    summary: str
    citations: list[str] = []
    prompt_hash: str | None = None
    model_deployment: str | None = None
    invocation_id: str


def _resolve_model_key() -> str:
    return os.getenv("AZURE_AI_SIMULATION_MODEL_KEY") or os.getenv("AZURE_AI_REASONING_MODEL_KEY") or "simulation"


def _build_foundry_client() -> LiveFoundryChatClient | None:
    endpoint = os.getenv("AZURE_AI_PROJECT_ENDPOINT")
    if not endpoint:
        return None
    try:
        return LiveFoundryChatClient(endpoint=endpoint)
    except Exception:  # noqa: BLE001
        logger.warning("Dispatcher Foundry client unavailable; degraded stub replies in effect", exc_info=True)
        return None


def create_app() -> FastAPI:
    """FastAPI app factory used by the ``__main__`` runner and unit tests."""
    app = FastAPI(title="AMA Sub-Agent Dispatcher", version="1.0.0")
    foundry_client = _build_foundry_client()
    model_key = _resolve_model_key() if foundry_client is not None else None
    if foundry_client is not None and model_key is None:
        logger.warning(
            "Dispatcher could not resolve a chat model key from environment; degraded stub replies in effect"
        )

    @app.get("/health")
    async def health() -> dict[str, str]:
        return {
            "status": "ok",
            "service": "sub-agent-dispatcher",
            "llm": "ready" if (foundry_client is not None and model_key) else "degraded",
        }

    @app.post("/{role}/invoke", response_model=InvokeResponse)
    async def invoke(role: str, body: InvokeRequest) -> InvokeResponse:
        if role not in _ROLES:
            raise HTTPException(status_code=404, detail=f"unknown sub-agent role '{role}'")

        invocation_id = uuid4().hex
        system_prompt = _ROLE_SYSTEM[role]
        prompt_body = f"{system_prompt}\n\nQuestion:\n{body.question}".strip()
        prompt_hash = hashlib.sha256(prompt_body.encode("utf-8")).hexdigest()

        summary = ""
        deployment_used: str | None = None

        if foundry_client is not None and model_key:
            try:
                response = foundry_client.chat_complete(
                    model_key=model_key,
                    messages=[
                        {"role": "system", "content": system_prompt},
                        {"role": "user", "content": body.question},
                    ],
                    max_tokens=int(os.getenv("SUBAGENT_LLM_MAX_TOKENS", "400")),
                    timeout_s=float(os.getenv("SUBAGENT_LLM_TIMEOUT_S", "60")),
                )
                summary = response.text.strip()
                deployment_used = response.raw.get("deployment") if isinstance(response.raw, dict) else None
            except FoundryGatewayDenied as exc:
                logger.info(
                    "subagent.gateway_denied role=%s tenant=%s invocation=%s reason=%s",
                    role,
                    body.tenant_id,
                    invocation_id,
                    exc.reason,
                )
                summary = "[classification-denied] payload blocked by sovereignty gateway"
            except (FoundryConfigurationError, FoundryTransportError):
                logger.exception(
                    "subagent.foundry_error role=%s tenant=%s invocation=%s",
                    role,
                    body.tenant_id,
                    invocation_id,
                )
            except Exception:  # noqa: BLE001
                logger.exception(
                    "subagent.llm_failed role=%s tenant=%s invocation=%s",
                    role,
                    body.tenant_id,
                    invocation_id,
                )

        if not summary:
            # Deterministic, simulation-marked stub. Returned only when the
            # LLM is unavailable or returned an empty completion — keeps the
            # Controller's tool round-trip useful instead of erroring.
            summary = (
                f"[{role}] (degraded) No grounded answer available; consider the "
                f"following operational frame: {body.question.strip()[:200]}"
            )

        logger.info(
            "subagent.invoke role=%s tenant=%s invocation=%s deployment=%s len=%d",
            role,
            body.tenant_id,
            invocation_id,
            deployment_used,
            len(summary),
        )

        return InvokeResponse(
            summary=summary,
            citations=[],
            prompt_hash=prompt_hash,
            model_deployment=deployment_used,
            invocation_id=invocation_id,
        )

    return app


app = create_app()
