"""Review log CLI (T050 + T157 + T158).

Builds ``specs/034-webapp-capstone-coverage/review-log.md`` from agent
objections collected by the nightly tribunal. Each row is one
``ReviewVote`` from the contract, derived from
``.github/agents/{panel}/{agent_id}.agent.md`` plus an optional sibling
``{agent_id}.objection.json``.

Subcommands:

  vote       Append one vote (used by the GitHub Action).
  panel      Resolve all votes for one panel + cycle (deduplicates against
             gap status; emits dispositions per the contract veto rules).
  list       Print the log JSON to stdout.
"""

from __future__ import annotations

import argparse
import json
import sys
from datetime import UTC, datetime
from pathlib import Path

# Ensure ``_lib`` is importable when this CLI is invoked from any cwd.
sys.path.insert(0, str(Path(__file__).resolve().parent))

from _lib.audit_append import append_audit  # noqa: E402, I001
from _lib.schema_validators import validate_or_raise  # noqa: E402, I001


REPO_ROOT = Path(__file__).resolve().parents[2]
SPEC_ROOT = REPO_ROOT / "specs" / "034-webapp-capstone-coverage"
LOG_MD = SPEC_ROOT / "review-log.md"
LOG_JSON = SPEC_ROOT / "review-log.json"
AUDIT_ROOT = SPEC_ROOT / "_evidence" / "audit" / "web-coverage-review"


def load_log() -> list[dict]:
    if not LOG_JSON.exists():
        return []
    payload = json.loads(LOG_JSON.read_text(encoding="utf-8"))
    return payload if isinstance(payload, list) else []


def save_log(votes: list[dict]) -> None:
    SPEC_ROOT.mkdir(parents=True, exist_ok=True)
    LOG_JSON.write_text(
        json.dumps(votes, indent=2, sort_keys=True, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )
    _render_markdown(votes)


def _render_markdown(votes: list[dict]) -> None:
    lines = [
        "# Web Coverage Review Log (spec 034)",
        "",
        "_Autogenerated by `scripts/web-coverage/review-log.py`. Do not edit by hand._",
        "",
        "Each row is one tribunal vote against a gap (cycle 0..3 + escalation cycle 4).",
        "",
        "| Cycle | Panel | Agent | Gap | Vote | Disposition | FRs | Recorded |",
        "| --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for v in votes:
        lines.append(
            f"| {v['cycle']} | {v['panel']} | `{v['agent_id']}` | {v['gap_id']} | {v['vote']} "
            f"| {v['disposition']} | {', '.join(v['touched_frs'])} | {v['recorded_at']} |",
        )
    LOG_MD.write_text("\n".join(lines) + "\n", encoding="utf-8")


def cmd_vote(args: argparse.Namespace) -> None:
    vote = {
        "agent_id": args.agent_id,
        "panel": args.panel,
        "cycle": args.cycle,
        "gap_id": args.gap_id,
        "touched_personas": args.personas,
        "touched_frs": args.frs,
        "touched_clauses": args.clauses,
        "vote": args.vote,
        "rationale": args.rationale or ("" if args.vote == "approve" else "(no rationale provided)"),
        "disposition": args.disposition,
        "recorded_at": datetime.now(UTC).isoformat(timespec="seconds"),
    }
    validate_or_raise("review-vote", vote)
    votes = load_log()
    votes.append(vote)
    save_log(votes)
    append_audit(AUDIT_ROOT, "vote-recorded", {"agent": args.agent_id, "gap": args.gap_id, "cycle": args.cycle})


def cmd_panel(args: argparse.Namespace) -> None:
    """Resolve all votes for a panel × cycle (T158).

    Computes:
      • ``meritorious``     — at least 2/3 of the *relevant* panel approved.
      • ``operational_veto`` — operational panel objected on a safety-critical
                               clause {I, IV, NN-1, NN-2, QG-1}; this overrides
                               an otherwise-meritorious vote.
      • ``override``        — supermajority (≥ 50% + 1) of *all 85 agents*
                               sustained an operational veto.
      • ``pending``         — quorum not reached.

    Side effect: writes one PR-ready spec-amendment stub per resolved gap to
    ``specs/034-…/diffs/{cycle}/{gap_id}.md`` so iteration_loop can open a PR.
    """

    SAFETY_CRITICAL = {"I", "IV", "NN-1", "NN-2", "QG-1"}
    OPERATIONAL_PANEL_SIZE = 30  # spec.md: 30 operational + 35 sector + 20 technical = 85
    TOTAL_AGENTS = 85

    votes = load_log()
    matching = [v for v in votes if v["panel"] == args.panel and v["cycle"] == args.cycle]
    by_gap: dict[str, list[dict]] = {}
    for v in matching:
        by_gap.setdefault(v["gap_id"], []).append(v)

    diffs_root = SPEC_ROOT / "diffs" / f"cycle-{args.cycle}"
    diffs_root.mkdir(parents=True, exist_ok=True)

    resolutions: list[dict] = []
    for gap_id, group in by_gap.items():
        approve = sum(1 for v in group if v["vote"] == "approve")
        object_count = sum(1 for v in group if v["vote"] == "object")
        # abstain doesn't count toward quorum either way; FR cite Q13.
        relevant = approve + object_count
        meritorious = relevant >= 1 and approve / max(relevant, 1) >= 2 / 3

        # Operational veto — only on safety-critical clauses.
        op_vetoes = [
            v for v in votes
            if v["gap_id"] == gap_id
            and v["panel"] == "operational"
            and v["vote"] == "object"
            and any(c in SAFETY_CRITICAL for c in v.get("touched_clauses", []))
        ]
        operational_veto = bool(op_vetoes) and args.panel in {"sector", "technical"}

        # Override — count distinct agents across all panels who voted approve
        # for this gap in any cycle ≤ args.cycle.
        override_voters = {
            v["agent_id"]
            for v in votes
            if v["gap_id"] == gap_id and v["vote"] == "approve" and v["cycle"] <= args.cycle
        }
        override_threshold = TOTAL_AGENTS // 2 + 1
        override = operational_veto and len(override_voters) >= override_threshold

        if override:
            disposition = "override"
        elif operational_veto:
            disposition = "veto"
        elif meritorious:
            disposition = "meritorious"
        elif relevant > 0:
            disposition = "rejected"
        else:
            disposition = "pending"

        resolutions.append({
            "gap_id": gap_id,
            "panel": args.panel,
            "cycle": args.cycle,
            "approve": approve,
            "object": object_count,
            "abstain": sum(1 for v in group if v["vote"] == "abstain"),
            "operational_veto": operational_veto,
            "operational_veto_size": len(op_vetoes),
            "override": override,
            "override_voters": len(override_voters),
            "override_threshold": override_threshold,
            "disposition": disposition,
        })

        # Emit a PR-ready spec amendment stub per resolved gap.
        diff_path = diffs_root / f"{gap_id}.md"
        diff_path.write_text(
            "\n".join([
                f"# {gap_id} — {args.panel} panel resolution (cycle {args.cycle})",
                "",
                "_Generated by `scripts/web-coverage/review-log.py panel`._",
                "",
                f"- Disposition: **{disposition}**",
                f"- Approve / object / abstain: {approve} / {object_count} / "
                f"{sum(1 for v in group if v['vote'] == 'abstain')}",
                f"- Operational veto: {'yes' if operational_veto else 'no'}",
                f"- Override supermajority: {len(override_voters)}/{override_threshold}",
                "",
                "## Proposed action",
                "",
                "TODO: spec amendment text — link gap-register row to closing PR.",
                "",
            ]) + "\n",
            encoding="utf-8",
        )

    summary = {
        "panel": args.panel,
        "cycle": args.cycle,
        "total_panel_size_hint": OPERATIONAL_PANEL_SIZE if args.panel == "operational" else None,
        "vote_count": len(matching),
        "gaps_resolved": len(by_gap),
        "resolutions": resolutions,
    }
    json.dump(summary, sys.stdout, indent=2, sort_keys=True)
    sys.stdout.write("\n")
    append_audit(AUDIT_ROOT, "panel-resolved", {"panel": args.panel, "cycle": args.cycle, "gaps": len(by_gap)})


def cmd_list(_args: argparse.Namespace) -> None:
    json.dump(load_log(), sys.stdout, indent=2, sort_keys=True)
    sys.stdout.write("\n")


def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="command", required=True)

    p_vote = sub.add_parser("vote", help="append a tribunal vote")
    p_vote.add_argument("--agent-id", required=True)
    p_vote.add_argument("--panel", choices=["operational", "sector", "technical"], required=True)
    p_vote.add_argument("--cycle", type=int, choices=[0, 1, 2, 3, 4], required=True)
    p_vote.add_argument("--gap-id", required=True)
    p_vote.add_argument("--personas", nargs="+", required=True)
    p_vote.add_argument("--frs", nargs="+", required=True)
    p_vote.add_argument("--clauses", nargs="+", required=True)
    p_vote.add_argument(
        "--vote",
        choices=["approve", "object", "abstain"],
        required=True,
    )
    p_vote.add_argument(
        "--disposition",
        choices=["meritorious", "rejected", "veto", "override", "pending"],
        required=True,
    )
    p_vote.add_argument("--rationale", default="")
    p_vote.set_defaults(func=cmd_vote)

    p_panel = sub.add_parser("panel", help="resolve a panel × cycle disposition summary")
    p_panel.add_argument("--panel", choices=["operational", "sector", "technical"], required=True)
    p_panel.add_argument("--cycle", type=int, choices=[0, 1, 2, 3, 4], required=True)
    p_panel.set_defaults(func=cmd_panel)

    p_list = sub.add_parser("list", help="print review log JSON to stdout")
    p_list.set_defaults(func=cmd_list)

    return p


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    args.func(args)
    return 0


if __name__ == "__main__":  # pragma: no cover - CLI entry point
    sys.exit(main())
