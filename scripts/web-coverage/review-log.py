"""Review log CLI (T050 + T157 + T158 + T203).

Builds ``specs/034-webapp-capstone-coverage/review-log.md`` from agent
objections collected by the nightly tribunal. Each row is one
``ReviewVote`` from the contract, derived from
``.github/agents/{panel}/{agent_id}.agent.md`` plus an optional sibling
``{agent_id}.objection.json``.

Subcommands:

  vote       Append one vote (used by the GitHub Action).
  panel      Resolve all votes for one panel + cycle (deduplicates against
             gap status; emits dispositions per the contract veto rules).
  list       Print the log JSON to stdout.
  closure    Compute the SC-012 closure ratio for a given cycle_id from
             ``_artifacts/cycle-metadata.json`` and the gap register;
             opens a meta-gap GAP-CYCLE-{id}-CLOSURE-RATE-LOW when the
             ratio falls below 0.80 (FR-005 + Q22 + CHK210..212).
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from datetime import UTC, datetime
from pathlib import Path

# Ensure ``_lib`` is importable when this CLI is invoked from any cwd.
sys.path.insert(0, str(Path(__file__).resolve().parent))

from _lib.audit_append import append_audit  # noqa: E402, I001
from _lib.schema_validators import validate_or_raise  # noqa: E402, I001


REPO_ROOT = Path(__file__).resolve().parents[2]
SPEC_ROOT = REPO_ROOT / "specs" / "034-webapp-capstone-coverage"
LOG_MD = SPEC_ROOT / "review-log.md"
LOG_JSON = SPEC_ROOT / "review-log.json"
AUDIT_ROOT = SPEC_ROOT / "_evidence" / "audit" / "web-coverage-review"

# Cycle-1 amendment (T203): SC-012 closure measurement reads the active
# suite-run cycle metadata emitted by the Playwright reporter at
# onBegin (T182), and the gap-register state machine (T045 + T183).
CYCLE_METADATA_PATH = REPO_ROOT / "tests" / "e2e" / "web-coverage" / "_artifacts" / "cycle-metadata.json"
GAP_REGISTER_JSON = SPEC_ROOT / "gap-register.json"
GAP_REGISTER_CLI = Path(__file__).resolve().parent / "gap-register.py"
CLOSURE_RATIO_FLOOR = 0.80  # SC-012 / Q22 / CHK210
ITERATION_ESCALATED_AT = 4  # CHK211 — iteration_count >= 4 is escalated
UUID_V4_RE = re.compile(
    r"^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$",
    re.IGNORECASE,
)


def load_log() -> list[dict]:
    if not LOG_JSON.exists():
        return []
    payload = json.loads(LOG_JSON.read_text(encoding="utf-8"))
    return payload if isinstance(payload, list) else []


def save_log(votes: list[dict]) -> None:
    SPEC_ROOT.mkdir(parents=True, exist_ok=True)
    LOG_JSON.write_text(
        json.dumps(votes, indent=2, sort_keys=True, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )
    _render_markdown(votes)


def _render_markdown(votes: list[dict]) -> None:
    lines = [
        "# Web Coverage Review Log (spec 034)",
        "",
        "_Autogenerated by `scripts/web-coverage/review-log.py`. Do not edit by hand._",
        "",
        "Each row is one tribunal vote against a gap (cycle 0..3 + escalation cycle 4).",
        "",
        "| Cycle | Panel | Agent | Gap | Vote | Disposition | FRs | Recorded |",
        "| --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for v in votes:
        lines.append(
            f"| {v['cycle']} | {v['panel']} | `{v['agent_id']}` | {v['gap_id']} | {v['vote']} "
            f"| {v['disposition']} | {', '.join(v['touched_frs'])} | {v['recorded_at']} |",
        )
    LOG_MD.write_text("\n".join(lines) + "\n", encoding="utf-8")


def cmd_vote(args: argparse.Namespace) -> None:
    vote = {
        "agent_id": args.agent_id,
        "panel": args.panel,
        "cycle": args.cycle,
        "gap_id": args.gap_id,
        "touched_personas": args.personas,
        "touched_frs": args.frs,
        "touched_clauses": args.clauses,
        "vote": args.vote,
        "rationale": args.rationale or ("" if args.vote == "approve" else "(no rationale provided)"),
        "disposition": args.disposition,
        "recorded_at": datetime.now(UTC).isoformat(timespec="seconds"),
    }
    validate_or_raise("review-vote", vote)
    votes = load_log()
    votes.append(vote)
    save_log(votes)
    append_audit(AUDIT_ROOT, "vote-recorded", {"agent": args.agent_id, "gap": args.gap_id, "cycle": args.cycle})


def cmd_panel(args: argparse.Namespace) -> None:
    """Resolve all votes for a panel × cycle (T158).

    Computes:
      • ``meritorious``     — at least 2/3 of the *relevant* panel approved.
      • ``operational_veto`` — operational panel objected on a safety-critical
                               clause {I, IV, NN-1, NN-2, QG-1}; this overrides
                               an otherwise-meritorious vote.
      • ``override``        — supermajority (≥ 50% + 1) of *all 85 agents*
                               sustained an operational veto.
      • ``pending``         — quorum not reached.

    Side effect: writes one PR-ready spec-amendment stub per resolved gap to
    ``specs/034-…/diffs/{cycle}/{gap_id}.md`` so iteration_loop can open a PR.
    """

    SAFETY_CRITICAL = {"I", "IV", "NN-1", "NN-2", "QG-1"}
    OPERATIONAL_PANEL_SIZE = 30  # spec.md: 30 operational + 35 sector + 20 technical = 85
    TOTAL_AGENTS = 85

    votes = load_log()
    matching = [v for v in votes if v["panel"] == args.panel and v["cycle"] == args.cycle]
    by_gap: dict[str, list[dict]] = {}
    for v in matching:
        by_gap.setdefault(v["gap_id"], []).append(v)

    diffs_root = SPEC_ROOT / "diffs" / f"cycle-{args.cycle}"
    diffs_root.mkdir(parents=True, exist_ok=True)

    resolutions: list[dict] = []
    for gap_id, group in by_gap.items():
        approve = sum(1 for v in group if v["vote"] == "approve")
        object_count = sum(1 for v in group if v["vote"] == "object")
        # abstain doesn't count toward quorum either way; FR cite Q13.
        relevant = approve + object_count
        meritorious = relevant >= 1 and approve / max(relevant, 1) >= 2 / 3

        # Operational veto — only on safety-critical clauses.
        op_vetoes = [
            v for v in votes
            if v["gap_id"] == gap_id
            and v["panel"] == "operational"
            and v["vote"] == "object"
            and any(c in SAFETY_CRITICAL for c in v.get("touched_clauses", []))
        ]
        operational_veto = bool(op_vetoes) and args.panel in {"sector", "technical"}

        # Override — count distinct agents across all panels who voted approve
        # for this gap in any cycle ≤ args.cycle.
        override_voters = {
            v["agent_id"]
            for v in votes
            if v["gap_id"] == gap_id and v["vote"] == "approve" and v["cycle"] <= args.cycle
        }
        override_threshold = TOTAL_AGENTS // 2 + 1
        override = operational_veto and len(override_voters) >= override_threshold

        if override:
            disposition = "override"
        elif operational_veto:
            disposition = "veto"
        elif meritorious:
            disposition = "meritorious"
        elif relevant > 0:
            disposition = "rejected"
        else:
            disposition = "pending"

        resolutions.append({
            "gap_id": gap_id,
            "panel": args.panel,
            "cycle": args.cycle,
            "approve": approve,
            "object": object_count,
            "abstain": sum(1 for v in group if v["vote"] == "abstain"),
            "operational_veto": operational_veto,
            "operational_veto_size": len(op_vetoes),
            "override": override,
            "override_voters": len(override_voters),
            "override_threshold": override_threshold,
            "disposition": disposition,
        })

        # Emit a PR-ready spec amendment stub per resolved gap.
        diff_path = diffs_root / f"{gap_id}.md"
        diff_path.write_text(
            "\n".join([
                f"# {gap_id} — {args.panel} panel resolution (cycle {args.cycle})",
                "",
                "_Generated by `scripts/web-coverage/review-log.py panel`._",
                "",
                f"- Disposition: **{disposition}**",
                f"- Approve / object / abstain: {approve} / {object_count} / "
                f"{sum(1 for v in group if v['vote'] == 'abstain')}",
                f"- Operational veto: {'yes' if operational_veto else 'no'}",
                f"- Override supermajority: {len(override_voters)}/{override_threshold}",
                "",
                "## Proposed action",
                "",
                "TODO: spec amendment text — link gap-register row to closing PR.",
                "",
            ]) + "\n",
            encoding="utf-8",
        )

    summary = {
        "panel": args.panel,
        "cycle": args.cycle,
        "total_panel_size_hint": OPERATIONAL_PANEL_SIZE if args.panel == "operational" else None,
        "vote_count": len(matching),
        "gaps_resolved": len(by_gap),
        "resolutions": resolutions,
    }
    json.dump(summary, sys.stdout, indent=2, sort_keys=True)
    sys.stdout.write("\n")
    append_audit(AUDIT_ROOT, "panel-resolved", {"panel": args.panel, "cycle": args.cycle, "gaps": len(by_gap)})


def cmd_list(_args: argparse.Namespace) -> None:
    json.dump(load_log(), sys.stdout, indent=2, sort_keys=True)
    sys.stdout.write("\n")


# ---------- T203: SC-012 closure measurement ---------------------------------


def _read_cycle_metadata() -> dict | None:
    """Return the parsed reporter cycle metadata, or None if absent/invalid."""

    if not CYCLE_METADATA_PATH.exists():
        return None
    try:
        payload = json.loads(CYCLE_METADATA_PATH.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError):
        return None
    return payload if isinstance(payload, dict) else None


def _load_gap_register() -> list[dict]:
    if not GAP_REGISTER_JSON.exists():
        return []
    try:
        payload = json.loads(GAP_REGISTER_JSON.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError):
        return []
    return payload if isinstance(payload, list) else []


def _is_escalated(entry: dict) -> bool:
    """CHK211 escalation predicate.

    A row is escalated (excluded from BOTH numerator and denominator) when:
      • iteration_count >= ITERATION_ESCALATED_AT (Q22 ceiling), OR
      • status == "Escalated" (FR-024 escalate command), OR
      • owner contains the literal token "project-lead" (escalated:project-lead).
    """

    iteration = entry.get("iteration_count")
    if isinstance(iteration, int) and iteration >= ITERATION_ESCALATED_AT:
        return True
    if entry.get("status") == "Escalated":
        return True
    owner = entry.get("owner") or ""
    if isinstance(owner, str) and "project-lead" in owner.lower():
        return True
    return False


def _compute_closure(entries: list[dict], cycle_id: str) -> dict:
    """Compute the closure summary for one cycle.

    Numerator   = entries where status == "Closed" AND iteration_count < 4
                  AND not escalated.
    Denominator = entries (same cycle_id) where iteration_count < 4 AND
                  not escalated. Per CHK211, every row in the gap register
                  is by construction a merit-validated objection (only
                  meritorious tribunal dispositions open gaps).
    """

    in_cycle = [e for e in entries if e.get("cycle_id") == cycle_id]
    escalated = [e for e in in_cycle if _is_escalated(e)]
    eligible = [e for e in in_cycle if not _is_escalated(e)]
    closed = [e for e in eligible if e.get("status") == "Closed"]

    numerator = len(closed)
    denominator = len(eligible)
    ratio = (numerator / denominator) if denominator > 0 else 1.0

    return {
        "cycle_id": cycle_id,
        "computed_at": _now_iso(),
        "numerator": numerator,
        "denominator": denominator,
        "ratio": ratio,
        "ratio_floor": CLOSURE_RATIO_FLOOR,
        "passes_floor": ratio >= CLOSURE_RATIO_FLOOR,
        "closed_gap_ids": sorted(e["gap_id"] for e in closed),
        "raw_objection_gap_ids": sorted(e["gap_id"] for e in eligible),
        "escalated_gap_ids": sorted(e["gap_id"] for e in escalated),
    }


def _now_iso() -> str:
    return datetime.now(UTC).isoformat(timespec="seconds")


def _open_meta_gap(cycle_id: str, summary: dict) -> dict:
    """Open a meta-gap when closure < 80 %.

    Shells out to ``gap-register.py open`` so we go through the canonical
    state-machine + audit-append wiring rather than duplicating it.
    """

    short_id = cycle_id[:8]
    meta_gap_id = f"GAP-CYCLE-{short_id}-CLOSURE-RATE-LOW"
    notes = (
        f"Auto-opened by review-log.py closure for cycle_id={cycle_id}. "
        f"Closure ratio {summary['numerator']}/{summary['denominator']} = "
        f"{summary['ratio']:.3f} fell below floor {CLOSURE_RATIO_FLOOR:.2f} "
        f"(SC-012, Q22, CHK210). Carry-over for the next cycle."
    )
    cmd = [
        sys.executable,
        str(GAP_REGISTER_CLI),
        "open",
        "--gap-id",
        meta_gap_id,
        "--personas",
        "all",
        "--routes",
        "/",
        "--frs",
        "FR-005",
        "FR-024",
        "FR-010",
        "--clauses",
        "QG-1",
        "--owner",
        "project-lead",
        "--notes",
        notes,
    ]
    proc = subprocess.run(
        cmd,
        capture_output=True,
        text=True,
        cwd=REPO_ROOT,
        check=False,
    )
    return {
        "meta_gap_id": meta_gap_id,
        "exit_code": proc.returncode,
        "stdout": proc.stdout.strip(),
        "stderr": proc.stderr.strip(),
    }


def cmd_closure(args: argparse.Namespace) -> None:
    """SC-012 closure-ratio computation (T203).

    Reads the active cycle_id from --cycle-id (or falls back to
    _artifacts/cycle-metadata.json), filters gap-register entries by
    that cycle_id, applies CHK211 escalation exclusions, and emits
    numerator/denominator/ratio + raw lists to stdout. Audits the
    decision via append_audit so FR-010 has the full trail. When the
    ratio falls below CLOSURE_RATIO_FLOOR (0.80), opens a carry-over
    meta-gap via the gap-register CLI.
    """

    metadata = _read_cycle_metadata()
    cycle_id = args.cycle_id or (metadata or {}).get("cycle_id")
    if not cycle_id:
        sys.stderr.write(
            "review-log closure: no cycle_id supplied and "
            f"{CYCLE_METADATA_PATH} is missing or invalid — "
            "run a Playwright cycle first or pass --cycle-id\n",
        )
        raise SystemExit(2)
    if not UUID_V4_RE.match(cycle_id):
        sys.stderr.write(
            f"review-log closure: cycle_id '{cycle_id}' is not a UUID v4 "
            "(reporter contract violation)\n",
        )
        raise SystemExit(2)

    entries = _load_gap_register()
    summary = _compute_closure(entries, cycle_id)

    # CHK212: emit numerator + denominator + escalated-set + raw-objection
    # list to the audit timeline (FR-010) BEFORE flipping the meta-gap.
    append_audit(
        AUDIT_ROOT,
        "cycle-closure-computed",
        {
            "cycle_id": cycle_id,
            "numerator": summary["numerator"],
            "denominator": summary["denominator"],
            "ratio": summary["ratio"],
            "passes_floor": summary["passes_floor"],
            "raw_objection_count": len(summary["raw_objection_gap_ids"]),
            "escalated_count": len(summary["escalated_gap_ids"]),
        },
    )

    # CHK210: open a carry-over meta-gap when the cycle missed the floor.
    if not summary["passes_floor"] and not args.dry_run:
        summary["meta_gap"] = _open_meta_gap(cycle_id, summary)

    json.dump(summary, sys.stdout, indent=2, sort_keys=True)
    sys.stdout.write("\n")
    if not summary["passes_floor"]:
        # Non-zero exit so CI fails fast when SC-012 is breached and
        # operators see the carry-over meta-gap clearly.
        raise SystemExit(1)


def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="command", required=True)

    p_vote = sub.add_parser("vote", help="append a tribunal vote")
    p_vote.add_argument("--agent-id", required=True)
    p_vote.add_argument("--panel", choices=["operational", "sector", "technical"], required=True)
    p_vote.add_argument("--cycle", type=int, choices=[0, 1, 2, 3, 4], required=True)
    p_vote.add_argument("--gap-id", required=True)
    p_vote.add_argument("--personas", nargs="+", required=True)
    p_vote.add_argument("--frs", nargs="+", required=True)
    p_vote.add_argument("--clauses", nargs="+", required=True)
    p_vote.add_argument(
        "--vote",
        choices=["approve", "object", "abstain"],
        required=True,
    )
    p_vote.add_argument(
        "--disposition",
        choices=["meritorious", "rejected", "veto", "override", "pending"],
        required=True,
    )
    p_vote.add_argument("--rationale", default="")
    p_vote.set_defaults(func=cmd_vote)

    p_panel = sub.add_parser("panel", help="resolve a panel × cycle disposition summary")
    p_panel.add_argument("--panel", choices=["operational", "sector", "technical"], required=True)
    p_panel.add_argument("--cycle", type=int, choices=[0, 1, 2, 3, 4], required=True)
    p_panel.set_defaults(func=cmd_panel)

    p_list = sub.add_parser("list", help="print review log JSON to stdout")
    p_list.set_defaults(func=cmd_list)

    p_closure = sub.add_parser(
        "closure",
        help="compute the SC-012 closure ratio for a given cycle_id (T203)",
    )
    p_closure.add_argument(
        "--cycle-id",
        default=None,
        help="UUID v4 cycle_id to score; falls back to "
             "_artifacts/cycle-metadata.json when omitted",
    )
    p_closure.add_argument(
        "--dry-run",
        action="store_true",
        help="skip the carry-over GAP-CYCLE-{id}-CLOSURE-RATE-LOW open call "
             "(report-only mode)",
    )
    p_closure.set_defaults(func=cmd_closure)

    return p


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    args.func(args)
    return 0


if __name__ == "__main__":  # pragma: no cover - CLI entry point
    sys.exit(main())
