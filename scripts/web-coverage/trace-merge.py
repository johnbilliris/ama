"""Trace merge CLI (T048).

Merges N shard files (``coverage-trace.partial-*.json`` produced by the
custom Playwright reporter) into the canonical
``specs/034-webapp-capstone-coverage/coverage-trace.{md,json}`` artefacts.

Determinism contract (FR-006):

  • Rows are sorted by (persona_id, outcome, hazard, fr_id) before serialising.
  • The JSON is written with ``sort_keys=True`` and a trailing newline.
  • The markdown table is produced from the same sorted rows.

So running merge with the same shard inputs twice yields byte-identical files.
"""

from __future__ import annotations

import argparse
import json
import sys
from datetime import UTC, datetime
from pathlib import Path

# Ensure ``_lib`` is importable when this CLI is invoked from any cwd.
sys.path.insert(0, str(Path(__file__).resolve().parent))

from _lib.audit_append import append_audit  # noqa: E402, I001
from _lib.schema_validators import validate_or_raise  # noqa: E402, I001


REPO_ROOT = Path(__file__).resolve().parents[2]
SPEC_ROOT = REPO_ROOT / "specs" / "034-webapp-capstone-coverage"
DEFAULT_SHARD_GLOB = "coverage-trace.partial-*.json"
TRACE_MD = SPEC_ROOT / "coverage-trace.md"
TRACE_JSON = SPEC_ROOT / "coverage-trace.json"
AUDIT_ROOT = SPEC_ROOT / "_evidence" / "audit" / "web-coverage-trace"


def _sort_key(row: dict) -> tuple:
    return (
        row.get("persona_id", ""),
        row.get("outcome", 0),
        row.get("hazard", ""),
        row.get("fr_id", ""),
    )


def merge_rows(shards: list[Path]) -> list[dict]:
    rows: list[dict] = []
    seen: set[tuple] = set()
    for shard in shards:
        payload = json.loads(shard.read_text(encoding="utf-8"))
        for row in payload.get("rows", []):
            key = (row["persona_id"], row["outcome"], row["hazard"], row["fr_id"], tuple(row["test_ids"]))
            if key in seen:
                continue
            seen.add(key)
            validate_or_raise("coverage-trace-row", row)
            rows.append(row)
    rows.sort(key=_sort_key)
    return rows


def _resolve_generated_at(shards: list[Path]) -> str:
    """Pick the most recent ``generated_at`` from input shards.

    Determinism (FR-006): the merge step must produce byte-identical output
    when invoked twice with the same shards. Using ``datetime.now()`` here
    would violate that. Instead, take the max ``generated_at`` from the
    shards themselves — it is stable across re-runs while still reflecting
    when the underlying test runs completed.
    """
    timestamps: list[str] = []
    for shard in shards:
        payload = json.loads(shard.read_text(encoding="utf-8"))
        ts = payload.get("generated_at")
        if isinstance(ts, str) and ts:
            timestamps.append(ts)
    if timestamps:
        return max(timestamps)
    return datetime.fromtimestamp(0, tz=UTC).isoformat(timespec="seconds")


def render_markdown(rows: list[dict]) -> str:
    lines = [
        "# Web Coverage Trace (spec 034)",
        "",
        "_Autogenerated by `scripts/web-coverage/trace-merge.py`. Do not edit by hand._",
        "",
        "| Persona | AIIMS | Outcome | Hazard | FR | Clauses | Route | Tests | Status | Audit |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for row in rows:
        lines.append(
            f"| {row['persona_id']} | {row['aiims_function']} | {row['outcome']} | {row['hazard']} "
            f"| {row['fr_id']} | {', '.join(row['constitution_clauses'])} | `{row['route']}` "
            f"| {len(row['test_ids'])} | {row['status']} | "
            f"{row.get('audit_evidence_id') or '—'} |",
        )
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument(
        "--shards-dir",
        type=Path,
        default=REPO_ROOT / "tests" / "e2e" / "web-coverage" / "_artifacts",
        help="Directory containing coverage-trace.partial-*.json shard files.",
    )
    parser.add_argument("--shard-glob", default=DEFAULT_SHARD_GLOB)
    parser.add_argument("--output-json", type=Path, default=TRACE_JSON)
    parser.add_argument("--output-md", type=Path, default=TRACE_MD)
    args = parser.parse_args(argv)

    shards = sorted(args.shards_dir.glob(args.shard_glob))
    if not shards:
        sys.stderr.write(f"trace-merge: no shards found at {args.shards_dir}/{args.shard_glob}\n")
        # Emit empty canonical files so CI can still proceed deterministically.
        rows: list[dict] = []
    else:
        rows = merge_rows(shards)

    payload = {
        "generated_at": _resolve_generated_at(shards),
        "spec": "034-webapp-capstone-coverage",
        "schema_version": 1,
        "rows": rows,
    }
    args.output_json.parent.mkdir(parents=True, exist_ok=True)
    args.output_json.write_text(
        json.dumps(payload, indent=2, sort_keys=True, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )
    args.output_md.write_text(render_markdown(rows), encoding="utf-8")

    append_audit(AUDIT_ROOT, "trace-merged", {"shard_count": len(shards), "row_count": len(rows)})
    return 0


if __name__ == "__main__":  # pragma: no cover - CLI entry point
    sys.exit(main())
