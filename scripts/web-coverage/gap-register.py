"""Gap register state-machine CLI (T045 + T159 + T161).

Persists the FR-005 gap register as both:

  • Markdown source of truth at ``specs/034-…/gap-register.md``.
  • Append-only JSONL audit shadow at
    ``specs/034-…/_evidence/audit/web-coverage-gaps/{date}/{hour}.jsonl``.

State machine (FR-024, max 3 cycles):

  Open --in-progress--> In-Progress --close--> Closed --reopen--> Reopened
  Open --escalate--> Escalated  (only when iteration_count >= 3)

Subcommands:

  open       Create a new gap with status=Open, iteration_count=0.
  promote    Move Open -> In-Progress (must supply --pr-url).
  close      Move In-Progress -> Closed (must supply --merge-sha).
  regress    Reopen with --regression-evidence (FR-027); bumps iteration_count.
  escalate   Force status=Escalated; only legal when iteration_count >= 3.
  list       Print the current register as JSON to stdout.

Run ``python scripts/web-coverage/gap-register.py --help`` for full options.
"""

from __future__ import annotations

import argparse
import json
import sys
from datetime import UTC, datetime
from pathlib import Path

# Ensure ``_lib`` is importable when this CLI is invoked from any cwd.
sys.path.insert(0, str(Path(__file__).resolve().parent))

from _lib.audit_append import append_audit  # noqa: E402, I001
from _lib.schema_validators import validate_or_raise  # noqa: E402, I001


REPO_ROOT = Path(__file__).resolve().parents[2]
SPEC_ROOT = REPO_ROOT / "specs" / "034-webapp-capstone-coverage"
REGISTER_MD = SPEC_ROOT / "gap-register.md"
REGISTER_JSON = SPEC_ROOT / "gap-register.json"
AUDIT_ROOT = SPEC_ROOT / "_evidence" / "audit" / "web-coverage-gaps"
# Cycle-1 amendment (T183): suite-side cycle metadata emitted by the
# Playwright reporter at onBegin (T182). Optional — when present, new
# gap entries are stamped with cycle_id for FR-005 cross-cycle queries.
CYCLE_METADATA_PATH = REPO_ROOT / "tests" / "e2e" / "web-coverage" / "_artifacts" / "cycle-metadata.json"
MAX_ITERATION_CYCLES = 3


def _now_iso() -> str:
    return datetime.now(UTC).isoformat(timespec="seconds")


def _read_current_cycle_id() -> str | None:
    """Return the active cycle_id from the reporter's metadata file, or None.

    The file is written once per Playwright run by ``coverage-reporter.ts``
    (T182). It is gitignored — absence is normal in fresh checkouts and
    in CLI flows that pre-date Playwright (e.g. seeding a gap from a
    spec-review tribunal). When absent, gap entries simply omit the
    optional ``cycle_id`` field — the gap-register-entry schema accepts
    null/missing per the cycle-1 additive contract.
    """

    if not CYCLE_METADATA_PATH.exists():
        return None
    try:
        payload = json.loads(CYCLE_METADATA_PATH.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError):
        return None
    cycle_id = payload.get("cycle_id") if isinstance(payload, dict) else None
    return cycle_id if isinstance(cycle_id, str) else None


def load_register() -> list[dict]:
    if not REGISTER_JSON.exists():
        return []
    payload = json.loads(REGISTER_JSON.read_text(encoding="utf-8"))
    return payload if isinstance(payload, list) else []


def save_register(entries: list[dict]) -> None:
    SPEC_ROOT.mkdir(parents=True, exist_ok=True)
    REGISTER_JSON.write_text(
        json.dumps(entries, indent=2, sort_keys=True, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )
    _render_markdown(entries)


def _render_markdown(entries: list[dict]) -> None:
    lines = [
        "# Web Coverage Gap Register (spec 034)",
        "",
        "_Autogenerated by `scripts/web-coverage/gap-register.py`. Do not edit by hand._",
        "",
        "| Gap | Status | Owner | Iteration | FRs | Personas | PR | Updated |",
        "| --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for e in entries:
        pr = e.get("closing_pr_url") or "—"
        personas = ", ".join(e["affected_personas"][:3])
        suffix = "…" if len(e["affected_personas"]) > 3 else ""
        lines.append(
            f"| {e['gap_id']} | {e['status']} | {e['owner']} "
            f"| {e['iteration_count']}/{MAX_ITERATION_CYCLES} "
            f"| {', '.join(e['fr_ids'])} | {personas}{suffix} "
            f"| {pr} | {e['updated_at']} |",
        )
    REGISTER_MD.write_text("\n".join(lines) + "\n", encoding="utf-8")


def _find(entries: list[dict], gap_id: str) -> int:
    for i, e in enumerate(entries):
        if e["gap_id"] == gap_id:
            return i
    raise SystemExit(f"gap not found: {gap_id}")


def cmd_open(args: argparse.Namespace) -> None:
    entries = load_register()
    if any(e["gap_id"] == args.gap_id for e in entries):
        raise SystemExit(f"gap already exists: {args.gap_id}")
    entry = {
        "gap_id": args.gap_id,
        "affected_personas": args.personas,
        "affected_routes": args.routes,
        "fr_ids": args.frs,
        "constitution_clauses": args.clauses,
        "owner": args.owner,
        "status": "Open",
        "closing_pr_url": None,
        "merge_sha": None,
        "iteration_count": 0,
        "regression_evidence": None,
        "tribunal_notes": args.notes or "",
        "updated_at": _now_iso(),
    }
    # Cycle-1 amendment (T183, Q26): stamp the active cycle_id so FR-005
    # cross-cycle reads can group gaps by the suite-run that opened them.
    # Stays optional — null/missing is valid per the schema.
    cycle_id = _read_current_cycle_id()
    if cycle_id is not None:
        entry["cycle_id"] = cycle_id
    validate_or_raise("gap-register-entry", entry)
    entries.append(entry)
    save_register(entries)
    append_audit(AUDIT_ROOT, "gap-opened", {"gap_id": args.gap_id, "owner": args.owner})


def cmd_promote(args: argparse.Namespace) -> None:
    entries = load_register()
    idx = _find(entries, args.gap_id)
    entries[idx]["status"] = "In-Progress"
    entries[idx]["closing_pr_url"] = args.pr_url
    entries[idx]["updated_at"] = _now_iso()
    validate_or_raise("gap-register-entry", entries[idx])
    save_register(entries)
    append_audit(AUDIT_ROOT, "gap-promoted", {"gap_id": args.gap_id, "pr": args.pr_url})


def cmd_close(args: argparse.Namespace) -> None:
    entries = load_register()
    idx = _find(entries, args.gap_id)
    entries[idx]["status"] = "Closed"
    entries[idx]["merge_sha"] = args.merge_sha
    entries[idx]["closing_pr_url"] = args.pr_url or entries[idx].get("closing_pr_url")
    entries[idx]["updated_at"] = _now_iso()
    validate_or_raise("gap-register-entry", entries[idx])
    save_register(entries)
    append_audit(AUDIT_ROOT, "gap-closed", {"gap_id": args.gap_id, "merge_sha": args.merge_sha})


def cmd_regress(args: argparse.Namespace) -> None:
    """Reopen a previously closed gap with regression evidence (FR-027).

    Per data-model §2 invariants table: the Closed → Reopened transition resets
    ``iteration_count`` to 0 (a regression starts a fresh remediation budget),
    populates the ``regression_evidence`` block, and tags the row
    ``regression_detected``. The 3-cycle escalation guard (FR-024) still fires
    when a gap is regressed *and* the prior iteration_count was already at the
    cap; we honour that by escalating before the reset.
    """

    entries = load_register()
    idx = _find(entries, args.gap_id)
    entry = entries[idx]
    prior_count = entry["iteration_count"]
    if prior_count >= MAX_ITERATION_CYCLES:
        # FR-024 max-3-cycles guard: regress beyond cap forces escalation,
        # preserves the prior count for forensic traceability.
        entry["status"] = "Escalated"
    else:
        entry["status"] = "Reopened"
        entry["iteration_count"] = 0
    entry["regression_evidence"] = {
        "failing_test_id": args.failing_test_id,
        "reverted_commit_sha": args.reverted_commit_sha,
        "restored_revision_sha": args.restored_revision_sha,
        "detected_at": _now_iso(),
    }
    entry["regression_detected"] = True
    entry["updated_at"] = _now_iso()
    # Cycle-1 amendment (T183, Q26 + FR-027): re-stamp cycle_id when a
    # regression is detected — the FR-027 evidence cites the originating
    # cycle so panels can audit cycle history rather than relying on
    # detected_at timestamps alone.
    cycle_id = _read_current_cycle_id()
    if cycle_id is not None:
        entry["cycle_id"] = cycle_id
    validate_or_raise("gap-register-entry", entry)
    save_register(entries)
    append_audit(
        AUDIT_ROOT,
        "gap-regressed",
        {
            "gap_id": args.gap_id,
            "prior_iteration": prior_count,
            "status": entry["status"],
        },
    )


def cmd_escalate(args: argparse.Namespace) -> None:
    entries = load_register()
    idx = _find(entries, args.gap_id)
    entry = entries[idx]
    if entry["iteration_count"] < MAX_ITERATION_CYCLES:
        raise SystemExit(
            f"refusing to escalate: iteration_count={entry['iteration_count']} "
            f"< MAX_ITERATION_CYCLES ({MAX_ITERATION_CYCLES}). FR-024 guard.",
        )
    entry["status"] = "Escalated"
    entry["updated_at"] = _now_iso()
    validate_or_raise("gap-register-entry", entry)
    save_register(entries)
    append_audit(AUDIT_ROOT, "gap-escalated", {"gap_id": args.gap_id})


def _filter_by_cycle(entries: list[dict], cycle: str) -> list[dict]:
    """Apply the FR-005 ``--cycle current|all`` filter (T183, Q26).

    ``current`` keeps only rows whose ``cycle_id`` matches the active
    suite-run cycle (sourced from ``cycle-metadata.json``). When that
    file is absent (CLI run without a fresh Playwright invocation) we
    fall back to returning *all* rows so operators don't see an empty
    register; the caller logs a warning. ``all`` is opt-in and bypasses
    the filter — the canonical FR-005 + FR-027 cross-cycle read.
    """

    if cycle == "all":
        return list(entries)
    active = _read_current_cycle_id()
    if active is None:
        # No reporter run in this checkout — degrade to ``all`` so the
        # output is never empty for cycle-pre-aware callers. The CLI
        # surfaces a notice via stderr (handled by the caller).
        return list(entries)
    return [e for e in entries if e.get("cycle_id") == active]


def cmd_list(args: argparse.Namespace) -> None:
    entries = load_register()
    if args.cycle == "current" and _read_current_cycle_id() is None:
        sys.stderr.write(
            "notice: cycle-metadata.json missing — "
            "'--cycle current' degraded to 'all' (run Playwright reporter to refresh)\n",
        )
    entries = _filter_by_cycle(entries, args.cycle)
    json.dump(entries, sys.stdout, indent=2, sort_keys=True)
    sys.stdout.write("\n")


def cmd_validate(args: argparse.Namespace) -> None:
    """Re-validate every (filtered) entry against gap-register-entry.schema.json.

    Cycle-1 amendment (T183): operators run this in CI to catch drift
    after schema changes (e.g. the cycle_id additive field). Filter
    semantics mirror ``cmd_list``: ``--cycle current`` (default)
    validates only entries from the active suite-run; ``--cycle all``
    validates the entire register.
    """

    entries = load_register()
    if args.cycle == "current" and _read_current_cycle_id() is None:
        sys.stderr.write(
            "notice: cycle-metadata.json missing — "
            "'--cycle current' degraded to 'all' (run Playwright reporter to refresh)\n",
        )
    filtered = _filter_by_cycle(entries, args.cycle)
    failures: list[tuple[str, str]] = []
    for entry in filtered:
        try:
            validate_or_raise("gap-register-entry", entry)
        except Exception as exc:  # noqa: BLE001 - re-raise after report
            failures.append((entry.get("gap_id", "<unknown>"), str(exc)))
    if failures:
        for gap_id, msg in failures:
            sys.stderr.write(f"INVALID {gap_id}: {msg}\n")
        raise SystemExit(
            f"gap-register validate: {len(failures)}/{len(filtered)} entries failed schema",
        )
    sys.stdout.write(f"OK: {len(filtered)} entries validated (cycle={args.cycle})\n")


def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="command", required=True)

    p_open = sub.add_parser("open", help="create a new gap (status=Open)")
    p_open.add_argument("--gap-id", required=True)
    p_open.add_argument("--personas", nargs="+", required=True)
    p_open.add_argument("--routes", nargs="+", required=True)
    p_open.add_argument("--frs", nargs="+", required=True)
    p_open.add_argument("--clauses", nargs="+", required=True)
    p_open.add_argument("--owner", required=True)
    p_open.add_argument("--notes", default="")
    p_open.set_defaults(func=cmd_open)

    p_promote = sub.add_parser("promote", help="Open -> In-Progress")
    p_promote.add_argument("--gap-id", required=True)
    p_promote.add_argument("--pr-url", required=True)
    p_promote.set_defaults(func=cmd_promote)

    p_close = sub.add_parser("close", help="In-Progress -> Closed")
    p_close.add_argument("--gap-id", required=True)
    p_close.add_argument("--merge-sha", required=True)
    p_close.add_argument("--pr-url", default=None)
    p_close.set_defaults(func=cmd_close)

    p_regress = sub.add_parser("regress", help="Closed -> Reopened with evidence (FR-027)")
    p_regress.add_argument("--gap-id", required=True)
    p_regress.add_argument("--failing-test-id", required=True)
    p_regress.add_argument("--reverted-commit-sha", required=True)
    p_regress.add_argument("--restored-revision-sha", required=True)
    p_regress.set_defaults(func=cmd_regress)

    p_escalate = sub.add_parser("escalate", help="force Escalated (requires iteration >= 3)")
    p_escalate.add_argument("--gap-id", required=True)
    p_escalate.set_defaults(func=cmd_escalate)

    p_list = sub.add_parser("list", help="print register JSON to stdout")
    p_list.add_argument(
        "--cycle",
        choices=("current", "all"),
        default="current",
        help="filter by the active suite-run cycle (T183, Q26). 'current' "
             "uses cycle_id from cycle-metadata.json (FR-005 default); "
             "'all' is opt-in for FR-005 + FR-027 cross-cycle reads.",
    )
    p_list.set_defaults(func=cmd_list)

    p_validate = sub.add_parser(
        "validate",
        help="re-validate filtered entries against gap-register-entry.schema.json",
    )
    p_validate.add_argument(
        "--cycle",
        choices=("current", "all"),
        default="current",
        help="filter by the active suite-run cycle (T183, Q26). See 'list --help'.",
    )
    p_validate.set_defaults(func=cmd_validate)

    return p


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    args.func(args)
    return 0


if __name__ == "__main__":  # pragma: no cover - CLI entry point
    sys.exit(main())
