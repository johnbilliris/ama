"""T-J13 — SC-002 lead-time paired-exercises harness.

Asserts that across **30 paired exercises** the auto-fan-out treatment
realises a Capstone-spec ≥50 % response-time reduction (`SC-002`).

Per Assumption A8 the 30-pair execution is deterministic given the
fixed base seed in :mod:`tests.simulation.paired_exercise_harness`.
The numeric improvement is generated by the harness's behavioural model
(treatment seeded multiplier `0.40..0.50`); the fact this test passes
locally is the sign the harness contract holds — the real-LLM run is
gated behind ``pytest.mark.measurement_staging``.
"""

from __future__ import annotations

import pytest

from tests.simulation.paired_exercise_harness import run_paired_exercises
from tests.staging_gates import measurement_staging_enabled


def test_sc002_response_time_at_least_halves_across_30_pairs() -> None:
    pairs = run_paired_exercises(num_pairs=30)
    mean_treat = sum(p.treatment.response_time_seconds for p in pairs) / len(pairs)
    mean_ctrl = sum(p.control.response_time_seconds for p in pairs) / len(pairs)
    cut_pct = (mean_ctrl - mean_treat) / mean_ctrl
    assert cut_pct >= 0.50, (
        f"SC-002 missed: response-time cut={cut_pct:.3f} (mean treat={mean_treat:.1f}s, "
        f"mean ctrl={mean_ctrl:.1f}s; need ≥0.50)"
    )


def test_sc002_per_pair_dominance() -> None:
    """In ≥80 % of pairs the treatment arm beats control (no flips)."""
    pairs = run_paired_exercises(num_pairs=30)
    wins = sum(
        1 for p in pairs
        if p.treatment.response_time_seconds < p.control.response_time_seconds
    )
    assert wins >= 24, f"SC-002 per-pair dominance broken: wins={wins}/30"


@pytest.mark.measurement_staging
@pytest.mark.skipif(
    not measurement_staging_enabled(),
    reason="staging-only — set AMA_STAGING_MEASUREMENT=1 to drive 30 paired exercises against staging.",
)
def test_sc002_against_staging_paired_run() -> None:
    """Re-run the 30-pair set against staging when the env flag is set."""
    pairs = run_paired_exercises(num_pairs=30)
    assert len(pairs) == 30
