"""spec-038 T-AA047 — Pydantic ↔ TypeScript twin sync test.

Verifies the TS twin in ``packages/domain/src/help/index.ts`` exposes a
top-level ``export interface`` (or ``export type``) named exactly the same as
each Pydantic v2 entity in ``packages/domain/src/ama_domain/``.

We intentionally do NOT compare every field byte-by-byte (that would require
``ts-json-schema-generator`` in the Python test environment). Instead we
guard cardinality of the twin set so renaming a Pydantic entity without
updating the TS twin (or vice-versa) fails CI. Field-level drift is caught by
Phase 4 vitest contract tests + a future ts-schema generator integration.
"""

from __future__ import annotations

import re
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[3]
TWIN_FILE = REPO_ROOT / "packages" / "domain" / "src" / "help" / "index.ts"

# Source-of-truth entity names per data-model.md §1–§13 (Citation reused).
EXPECTED_ENTITIES = {
    "HelpArticle",
    "AnnotatedScreenshot",
    "Callout",
    "GlossaryTerm",
    "PersonaHelpProfile",
    "KnowledgeCorpusSource",
    "ChatSession",
    "ChatTurn",
    "HelpFeedback",
    "StalenessFlag",
    "SnapshotRecord",
    "Approver",
    "SupportHandoffRecord",
    "ContentReviewBacklogItem",
    "ChatAuditEntry",
    "Citation",
}


def test_twin_file_exists():
    assert TWIN_FILE.exists(), f"missing {TWIN_FILE}"


def test_every_entity_has_a_twin():
    src = TWIN_FILE.read_text(encoding="utf-8")
    declared = set(re.findall(r"export interface (\w+)", src)) | set(
        re.findall(r"export type (\w+)\s*=", src)
    )
    missing = EXPECTED_ENTITIES - declared
    extra = declared - EXPECTED_ENTITIES - {
        # auxiliary type-aliases generated by the twin
        "ArticleKind", "ArticleStatus", "ArticleDomain",
        "RefusalReason", "ChannelKind",
    }
    assert not missing, f"TS twins missing: {sorted(missing)}"
    # `extra` is informational — only flag if the twin grows unmoored entries
    assert not extra, f"TS twins not mirrored to Pydantic: {sorted(extra)}"


def test_citation_reexport():
    """T-AA043 — Citation type re-exported into the help bundle."""
    src = TWIN_FILE.read_text(encoding="utf-8")
    assert "export interface Citation" in src, "Citation twin missing from help bundle"


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(pytest.main([__file__]))
